"""실습 04: 2 → 8 → 2 신경망의 순전파를 확인합니다."""
import torch
from torch import nn

# 무작위로 생성되는 가중치(Weight)들을 고정하기 위해 시드(Seed)를 42로 설정합니다.
# 컴퓨터를 다시 켜거나 코드를 여러 번 실행해도 항상 똑같은 초기 예측값이 나오도록 보장합니다.
# 66, 195, 2019 등 아무 값으로 변경 하더라도 어떠한 문제도 되지 않음
torch.manual_seed(42)

# Sequential의 마지막 Linear를 수정해 출력 클래스 수가 2가 되게 하세요.
# 첫 Linear(2, 8)와 ReLU는 그대로 두세요. 모델 정의는 미리 제공했습니다.
# >>> B04
# TODO B04: 위 요구사항을 읽고 이 블록을 완성하세요.
# nn.Sequential은 레이어(층)들을 순서대로 연결하여 하나의 거대한 신경망 모델을 만드는 컨테이너입니다.
model = nn.Sequential(
    nn.Linear(2, 8),  # 1층: 입력 특징(Feature) 2개를 받아, 출력 특징 8개로 확장합니다. (2 → 8)
    nn.ReLU(),        # 활성화 함수: 음수 값은 0으로 만들고, 양수 값은 그대로 통과시켜 비선형성을 부여합니다. 하지만 기본강의 실습에서는 지워도 무방하다는거
    nn.Linear(8, 2)   # 2층: 1층의 출력 8개를 받아, 최종 예측 클래스 수인 2개로 줄입니다. (8 → 2)
)
# <<< B04

# X: 모델에 입력할 데이터 텐서입니다. 크기는 (4, 2)입니다.
# 즉, 2개의 특징(예: 키, 몸무게)을 가진 데이터 샘플이 총 4개 존재한다는 의미입니다.
X = torch.tensor([[1.0, 2.0], [3.0, 4.0], [0.0, 1.0], [2.0, 0.0]])

# 순전파(Forward Propagation) 연산: 입력 데이터 X를 모델에 통과시켜 예측값(logits)을 얻습니다.
logits = model(X)

# 형태(Shape)와 모델 구조 정보 출력
print("입력:", tuple(X.shape))       # 출력: (4, 2) -> 4개의 샘플, 각 샘플당 2개의 특징
print("출력:", tuple(logits.shape))  # 출력: (4, 2) -> 4개의 샘플, 각 샘플당 2개의 최종 클래스 예측 점수

# model.parameters()는 신경망이 학습하면서 업데이트할 모든 가중치(w)와 편향(b) 텐서들을 꺼내옵니다.
# p.numel()은 각 텐서에 포함된 숫자(원소)의 총 개수를 구해줍니다. 이들을 모두 더하면 전체 파라미터 수가 됩니다.
print("파라미터 수:", sum(p.numel() for p in model.parameters())) # 출력: 42
# logits는 원시 점수입니다. 이 시점에는 학습하지 않았습니다.

